"""Clearly-labelled example projects for demonstrations.

Seeding runs the *real* pipeline over the sample templates, so the examples
demonstrate the engine rather than replacing it.  Rows are marked
`kind = example_project` and the UI labels them as such everywhere.
"""

from __future__ import annotations

import logging

from app.database.project_store import ProjectStore
from app.schemas.analysis import AnalysisOptions, AnalysisRequest
from app.schemas.common import ProjectKind
from app.services.pipeline import get_pipeline
from app.services.templates import load_templates

logger = logging.getLogger("nyx.seed")

EXAMPLE_IDS = {
    "college-attendance": "prj-example-attendance",
    "online-examination": "prj-example-examination",
    "ecommerce-application": "prj-example-ecommerce",
}


def seed_example_projects(store: ProjectStore) -> int:
    """Insert the three demonstration scenarios when they are not present."""
    created = 0
    pipeline = get_pipeline()
    for template in load_templates():
        project_id = EXAMPLE_IDS.get(template.id)
        if project_id is None or store.exists(project_id):
            continue
        request = AnalysisRequest(
            requirements=template.requirements.model_copy(deep=True),
            options=AnalysisOptions(use_ai=False),
        )
        result = pipeline.run(request)
        store.save_result(
            result,
            project_id=project_id,
            kind=ProjectKind.EXAMPLE,
            name=f"{template.name} (example)",
            notes=(
                "Example project generated by NYX from a built-in template. It demonstrates a "
                f"{result.suitability.outcome.value.replace('_', ' ')} verdict: {result.suitability.headline}."
            ),
        )
        created += 1
        logger.info("seeded example %s -> %s", template.id, project_id)
    return created
